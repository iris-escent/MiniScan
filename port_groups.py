def _add_numeric_item(item, ports):
    if "-" in item:
        parts = item.split("-")
        if len(parts) != 2:
            raise ValueError(f"invalid port range: {item}")

        start = int(parts[0])
        end = int(parts[1])

        if start > end:
            raise ValueError("start port cannot be greater than end port")
        if start < 1 or end > 65535:
            raise ValueError("port must be between 1 and 65535")

        ports.update(range(start, end + 1))
        return

    port = int(item)
    if port < 1 or port > 65535:
        raise ValueError("port must be between 1 and 65535")
    ports.add(port)


def _add_spec(spec, ports):
    for item in spec.split(","):
        item = item.strip()
        if item:
            _add_numeric_item(item, ports)


def parse_ports(ports_text):
    ports = set()

    for item in ports_text.split(","):
        item = item.strip().lower()
        if not item:
            continue

        if item in PORT_GROUP_SPECS:
            _add_spec(PORT_GROUP_SPECS[item], ports)
            continue

        if item.isalpha():
            groups = ", ".join(PORT_GROUP_SPECS)
            raise ValueError(
                f"unknown port group: {item}; available groups: {groups}"
            )

        _add_numeric_item(item, ports)

    if not ports:
        raise ValueError("no ports specified")

    return sorted(ports)
